package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type Source struct {
	Name   string `json:"name"`
	Commit string `json:"commit"`
	Root   string `json:"-"`
}

type Conflict struct {
	ID      string
	Project string
	Detail  string
}

type MultiResult struct {
	Codes     map[string]CodeInfo
	RPCs      []RPC
	Conflicts []Conflict
	Expected  map[string][]string
	Unknown   []string
}

func DiscoverModules(root string) ([]Module, error) {
	entries, err := os.ReadDir(filepath.Join(root, "integrations"))
	if err != nil {
		return nil, err
	}
	out := []Module{}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		files, err := goFiles(filepath.Join(root, "integrations", e.Name()), false)
		if err != nil || len(files) == 0 {
			continue
		}
		out = append(out, Module{Name: e.Name(), Dir: "integrations/" + e.Name()})
	}
	return out, nil
}

func BuildMulti(sources []Source) (*MultiResult, error) {
	res := &MultiResult{Codes: map[string]CodeInfo{}, Expected: map[string][]string{}}
	byID := map[string]int{}
	for _, src := range sources {
		modules, err := DiscoverModules(src.Root)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", src.Name, err)
		}
		codes, err := ScanCodes(src.Root, modules)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", src.Name, err)
		}
		for code, info := range codes {
			if old, ok := res.Codes[code]; ok {
				info = CodeInfo{Status: old.Status, Modules: union(old.Modules, info.Modules)}
			}
			res.Codes[code] = info
		}
		rpcs, err := ScanRPCs(src.Root, modules)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", src.Name, err)
		}
		for _, r := range rpcs {
			i, ok := byID[r.ID]
			if !ok {
				r.Projects = []string{src.Name}
				byID[r.ID] = len(res.RPCs)
				res.RPCs = append(res.RPCs, r)
				continue
			}
			cur := &res.RPCs[i]
			cur.Projects = union(cur.Projects, []string{src.Name})
			if cur.Module != r.Module {
				res.Conflicts = append(res.Conflicts, Conflict{r.ID, src.Name, fmt.Sprintf("module %s here, %s kept", r.Module, cur.Module)})
				continue
			}
			for _, d := range shapeConflicts("request", map[string]any(cur.Request), map[string]any(r.Request)) {
				res.Conflicts = append(res.Conflicts, Conflict{r.ID, src.Name, d})
			}
			for _, d := range shapeConflicts("response", map[string]any(cur.Response), map[string]any(r.Response)) {
				res.Conflicts = append(res.Conflicts, Conflict{r.ID, src.Name, d})
			}
			cur.Request = asSchema(mergeKnown(map[string]any(cur.Request), map[string]any(r.Request)))
			cur.Response = asSchema(mergeKnown(map[string]any(cur.Response), map[string]any(r.Response)))
			cur.Errors = union(cur.Errors, r.Errors)
		}
		ids, unknown, err := RegisteredIDs(src.Root)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", src.Name, err)
		}
		for id := range ids {
			res.Expected[id] = union(res.Expected[id], []string{src.Name + ":" + ids[id]})
		}
		for _, u := range unknown {
			res.Unknown = append(res.Unknown, src.Name+": "+u)
		}
	}
	sort.Slice(res.RPCs, func(i, j int) bool { return res.RPCs[i].ID < res.RPCs[j].ID })
	return res, nil
}

func shapeConflicts(path string, a, b any) []string {
	am, aok := toMap(a)
	bm, bok := toMap(b)
	if !aok || !bok || len(am) == 0 || len(bm) == 0 {
		return nil
	}
	if am["type"] != bm["type"] {
		return []string{fmt.Sprintf("%s: %v kept, %v here", path, am["type"], bm["type"])}
	}
	out := []string{}
	switch am["type"] {
	case "object":
		ap, _ := toMap(am["properties"])
		bp, _ := toMap(bm["properties"])
		keys := []string{}
		for k := range bp {
			if _, ok := ap[k]; ok {
				keys = append(keys, k)
			}
		}
		sort.Strings(keys)
		for _, k := range keys {
			out = append(out, shapeConflicts(path+"."+k, ap[k], bp[k])...)
		}
	case "array":
		out = append(out, shapeConflicts(path+"[]", am["items"], bm["items"])...)
	}
	return out
}

func union(a, b []string) []string {
	seen := map[string]bool{}
	out := []string{}
	for _, list := range [][]string{a, b} {
		for _, s := range list {
			if !seen[s] {
				seen[s] = true
				out = append(out, s)
			}
		}
	}
	sort.Strings(out)
	return out
}

func WriteMulti(outDir string, sources []Source, res *MultiResult) error {
	codes, err := marshal(res.Codes)
	if err != nil {
		return err
	}
	doc := baseDocument(res.RPCs)
	doc.Comment = "Generated by tools/generate-all.sh from every project in tools/projects.txt; do not edit by hand."
	doc.Sources = sources
	schema, err := marshal(doc)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outDir, "codes.json"), codes, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "rpc-schema.json"), schema, 0o644)
}

func ReadExclude(path string) (map[string]string, error) {
	out := map[string]string{}
	if path == "" {
		return out, nil
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		id, reason, _ := strings.Cut(line, " ")
		out[id] = strings.TrimSpace(reason)
	}
	return out, nil
}

func DropExcluded(res *MultiResult, exclude map[string]string) {
	kept := res.RPCs[:0]
	for _, r := range res.RPCs {
		if _, ok := exclude[r.ID]; !ok {
			kept = append(kept, r)
		}
	}
	res.RPCs = kept
}

func CoverageReport(res *MultiResult, exclude map[string]string) []string {
	have := map[string]bool{}
	for _, r := range res.RPCs {
		have[r.ID] = true
	}
	ids := make([]string, 0, len(res.Expected))
	for id := range res.Expected {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	out := []string{}
	for _, id := range ids {
		if have[id] {
			continue
		}
		if _, ok := exclude[id]; ok {
			continue
		}
		out = append(out, fmt.Sprintf("%s registered in %s but has no wrapper", id, strings.Join(res.Expected[id], ", ")))
	}
	for _, u := range res.Unknown {
		out = append(out, "cannot read the RPC id of "+u)
	}
	for id := range exclude {
		if _, ok := res.Expected[id]; !ok {
			out = append(out, fmt.Sprintf("%s is in rpc-exclude.txt but no project registers it; remove the line", id))
		}
	}
	sort.Strings(out)
	return out
}
